-- SDL PSR Phase 4A: token storage table.
-- Review and execute only in the approved DEVELOPMENT/TEST Oracle schema.
-- This DDL is proposed; it does not alter BUSERS or SFM_EMP_INFO.

CREATE TABLE SDL_AUTH_TOKENS (
    TOKEN_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY
                      CONSTRAINT PK_SDL_AUTH_TOKENS PRIMARY KEY,
    EMP_ID            NUMBER(10,0) NOT NULL,
    LOGIN_ID          VARCHAR2(100 CHAR) NOT NULL,
    TOKEN_HASH        CHAR(64 CHAR) NOT NULL,
    TOKEN_TYPE        CHAR(1 CHAR) NOT NULL,
    FAMILY_ID         CHAR(32 CHAR) NOT NULL,
    PARENT_TOKEN_ID   NUMBER,
    REPLACED_BY_ID    NUMBER,
    CREATED_AT        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    EXPIRES_AT        TIMESTAMP WITH TIME ZONE NOT NULL,
    REVOKED_AT        TIMESTAMP WITH TIME ZONE,
    LAST_USED_AT      TIMESTAMP WITH TIME ZONE,
    CREATED_IP        VARCHAR2(45 CHAR),
    CONSTRAINT UQ_SDL_AUTH_TOKEN_HASH UNIQUE (TOKEN_HASH),
    CONSTRAINT CK_SDL_AUTH_TOKEN_TYPE CHECK (TOKEN_TYPE IN ('A', 'R')),
    CONSTRAINT FK_SDL_AUTH_TOKEN_PARENT
        FOREIGN KEY (PARENT_TOKEN_ID) REFERENCES SDL_AUTH_TOKENS (TOKEN_ID),
    CONSTRAINT FK_SDL_AUTH_TOKEN_REPLACED
        FOREIGN KEY (REPLACED_BY_ID) REFERENCES SDL_AUTH_TOKENS (TOKEN_ID)
);

CREATE INDEX IX_SDL_AUTH_TOKEN_EMP
    ON SDL_AUTH_TOKENS (EMP_ID, TOKEN_TYPE);

CREATE INDEX IX_SDL_AUTH_TOKEN_FAMILY
    ON SDL_AUTH_TOKENS (FAMILY_ID);

